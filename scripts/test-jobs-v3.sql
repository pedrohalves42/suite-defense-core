-- Use este script para validar que a implementacao de Jobs v3
-- esta funcionando corretamente end-to-end.
--
-- Jobs v3 usam o endpoint submit-job-result e preenchem:
-- - output (JSON com resultado da execucao)
-- - execution_time_seconds
-- - started_at, finished_at
-- - error_message (se falhou)
--
-- PRE-REQUISITOS:
-- 1. Script do agente sincronizado: npm run sync:agent
-- 2. Pelo menos 1 agente ativo no sistema
-- 3. Agente deve ter funcao Submit-JobResult implementada
