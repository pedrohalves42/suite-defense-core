-- Verificar status do job de teste
SELECT 
  id,
  agent_name,
  type,
  status,
  output IS NOT NULL AS is_v3,
  output,
  execution_time_seconds,
  started_at,
  finished_at,
  error_message,
  created_at
FROM jobs
WHERE type = 'integration_test_v3'
ORDER BY created_at DESC
LIMIT 1;

