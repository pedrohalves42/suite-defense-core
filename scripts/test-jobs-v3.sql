-- ????????????????????????????????????????????????????????????
-- PARTE 1: Criar Job de Teste v3
-- ????????????????????????????????????????????????????????????

-- Este job sera criado com status 'queued' e deve ser processado
-- pelo agente ativo nos proximos 60 segundos

INSERT INTO jobs (
  id,
  agent_name,
  type,
  payload,
  status,
  tenant_id,
  created_at
)
SELECT
  gen_random_uuid(),
  a.agent_name,
  'integration_test_v3',
  jsonb_build_object(
    'message', 'Test Jobs v3 implementation',
    'timestamp', NOW(),
    'test_id', gen_random_uuid()
  ),
  'queued',
  a.tenant_id,
  NOW()
FROM agents a
WHERE a.status = 'active'
  AND a.last_heartbeat > NOW() - INTERVAL '5 minutes'
ORDER BY a.last_heartbeat DESC
LIMIT 1;

